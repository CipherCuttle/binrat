import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { canonicalJson } from "../web/snapshot-contract.js";

const hash = value => createHash("sha256").update(typeof value === "string" || Buffer.isBuffer(value) ? value : canonicalJson(value)).digest("hex");
const generated = path => path.startsWith("src/public/generated/") || path === "web/release.json" || path === "node_modules";
const files = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "-z"], { encoding: "utf8" })
  .split("\0").filter(path => path && !generated(path) && !path.startsWith("node_modules/"));
const sourceFiles = files.sort().map(path => ({ path, sha256: hash(readFileSync(path)) }));
const dirty = execFileSync("git", ["status", "--porcelain=v1", "-z"], { encoding: "utf8" }).split("\0")
  .filter(entry => entry && !generated(entry.slice(3)));
const sourceSha = execFileSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const manifest = JSON.parse(readFileSync("docs/CAPABILITY_MANIFEST_V0.json", "utf8"));
const config = JSON.parse(readFileSync("cloudflare/wrangler.example.jsonc", "utf8").replace(/^\s*\/\/.*$/gm, ""));
const worker = readFileSync("src/cloudflare/worker.ts", "utf8");
const ttls = [...worker.matchAll(/public, max-age=\d+, s-maxage=(\d+),/g)].map(match => Number(match[1]) * 1000);
if (config.triggers.crons[0] !== "* * * * *" || ttls.length < 2) throw new Error("PUBLIC_RUNTIME_CADENCE_UNRESOLVED");
const auditPath = "docs/public-evidence/sniffer-prospective-confirmation-20261006-v1/audit.json";
const auditRaw = existsSync(auditPath) ? readFileSync(auditPath) : null;
const auditSha256 = auditRaw && hash(auditRaw);
const snifferAudit = auditSha256 === "3f242a4e230fe911c57256768d273496956b5d0114040c5346e65338e838ba5b" ? JSON.parse(auditRaw) : null;
const material = {
  schemaVersion: "binrat.public-release/1", sourceSha, sourceTreeDigest: hash(sourceFiles), sourceClean: dirty.length === 0,
  manifestRevision: manifest.updatedAt ?? null, manifestDigest: hash(canonicalJson(manifest)),
  mappingDigest: files.includes("src/public/productProjection.ts") ? hash(readFileSync("src/public/productProjection.ts")) : null,
  assetsDigest: hash(sourceFiles.filter(file => file.path.startsWith("web/"))),
  runtimeSemantics: { configurationSource: "cloudflare/wrangler.example.jsonc + Worker cache headers", publicationIntervalMs: 60_000,
    statusCacheTtlMs: ttls[0], feedSharedCacheTtlMs: ttls[1], maxStatusAgeMs: Number(config.vars.BINRAT_MAX_STATUS_AGE_MS) },
};
const release = { ...material, buildId: hash(material) };
mkdirSync("src/public/generated", { recursive: true });
mkdirSync(".artifacts/public-truth", { recursive: true });
writeFileSync("src/public/generated/releaseIdentity.ts", `// Generated by scripts/build-public-release.mjs.\nexport const publicReleaseIdentity = ${JSON.stringify(release, null, 2)} as const;\n`);
writeFileSync("src/public/generated/researchEvidence.ts", `// Derived from the pinned existing research audit; no mutable status literal.\nexport const researchEvidence = ${JSON.stringify({ auditSha256, audit: snifferAudit }, null, 2)} as const;\n`);
writeFileSync("web/release.json", JSON.stringify(release, null, 2) + "\n");
writeFileSync(".artifacts/public-truth/source-receipt.json", JSON.stringify({ release, sourceFiles }, null, 2) + "\n");
console.log(`PUBLIC_RELEASE_BUILD ${release.buildId} source=${sourceSha} clean=${release.sourceClean}`);
